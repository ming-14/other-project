"""!
@file config.py
@brief 3D迷宫RayCasting游戏的配置常量

定义游戏运行所需的全局参数，包括迷宫尺寸、玩家移动速度、
渲染视野(FOV)、颜色调色板以及终端渲染相关参数。
"""

import math

# ============================================================================
# 迷宫配置
# ============================================================================
## 迷宫单元格数（必须为奇数，便于递归回溯生成算法在奇数格上开辟通道）
MAZE_WIDTH = 21
## 迷宫高度（必须为奇数）
MAZE_HEIGHT = 21

# ============================================================================
# 玩家配置
# ============================================================================
## 玩家视野角度（弧度），90度接近现代FPS默认视野
## 值越大视野越广但边缘畸变越明显，66°为Wolfenstein3D经典值
FOV = math.radians(90.0)
## 每帧移动速度（单元格/帧）
MOVE_SPEED = 0.06
## 每帧旋转速度（弧度/帧）
ROTATE_SPEED = 0.045
## 碰撞检测时与墙壁保持的安全距离，避免穿墙
WALL_PADDING = 0.2

# ============================================================================
# 渲染配置
# ============================================================================
## 目标帧率
TARGET_FPS = 30
## 小地图单元格在屏幕上占据的像素数（虚拟像素，2个=1终端行）
MINIMAP_SCALE = 1

# ============================================================================
# 性能优化配置
# ============================================================================
## 渲染策略选择（三选一）：
##   'ansi'       - ANSI 24位真彩色 + RLE游程编码（跨平台，色彩最丰富）
##   'quantize'   - 量化颜色 + ANSI + RLE（牺牲色彩换IO压缩，适合慢终端）
##   'bypass_ansi' - Win32 WriteConsoleOutput直接缓冲区输出（仅cmd，16色）
RENDER_STRATEGY = 'ansi'

## 量化参数（仅RENDER_STRATEGY='quantize'时生效）
## 每通道保留的有效位数（取值1-8）。
## 8=不量化(256级)，5=32级，4=16级，3=8级。
## 值越小量化越激进、IO数据越少但色彩越粗糙。推荐4-5。
COLOR_QUANTIZE_BITS = 3

## 兼容旧代码的派生开关（由RENDER_STRATEGY自动推导，勿手动修改）
COLOR_QUANTIZE_ENABLED = (RENDER_STRATEGY == 'quantize')
BYPASS_ANSI_ENABLED = (RENDER_STRATEGY == 'bypass_ansi')

# ============================================================================
# 光照与雾化系统
# ============================================================================
## 雾化起始距离（此距离内保持全亮，单位：格）
FOG_NEAR = 1.2
## 雾化终止距离（此距离外衰减至最小亮度，单位：格）
FOG_FAR = 13.0
## 雾化曲线指数（>1中段衰减更陡峭，近亮远暗对比更明显）
FOG_GAMMA = 1.6
## 最小亮度系数（最远处保留的亮度比例，避免全黑看不清）
MIN_BRIGHTNESS = 0.05
## 东西墙侧光压暗系数（模拟侧光，区分墙面朝向）
WALL_SIDE_SHADE = 0.68
## 墙面纵向环境光遮蔽强度（上下边缘变暗比例，0=无，0.5=上下暗50%）
WALL_VERTICAL_SHADE = 0.40
## 墙面条纹纹理周期（世界坐标单位，0=禁用纹理）
WALL_STRIPE_PERIOD = 0.0
## 墙面条纹纹理对比度（0=无明暗差，0.3=30%明暗变化）
WALL_STRIPE_CONTRAST = 0.0
## 玩家眼高（单位：格，用于地板/天花板距离反推）
PLAYER_EYE_HEIGHT = 0.5

# ============================================================================
# 颜色调色板（R, G, B）
# ============================================================================
## 天花板顶部颜色（深蓝）
CEILING_TOP = (15, 15, 35)
## 天花板靠近地平线颜色
CEILING_BOTTOM = (35, 35, 65)
## 地板靠近地平线颜色
FLOOR_TOP = (40, 35, 30)
## 地板近处颜色（较亮）
FLOOR_BOTTOM = (70, 60, 50)

## 南北向墙面基色（较亮）
WALL_NS_COLOR = (150, 150, 175)
## 东西向墙面基色（较暗，用于区分朝向）
WALL_EW_COLOR = (100, 100, 130)
## 出口墙面基色（绿色，醒目）
EXIT_COLOR = (60, 200, 90)

## 小地图墙壁颜色
MINIMAP_WALL = (90, 90, 120)
## 小地图通道颜色
MINIMAP_PATH = (20, 20, 30)
## 小地图玩家位置颜色
MINIMAP_PLAYER = (240, 240, 80)
## 小地图出口颜色
MINIMAP_EXIT = (60, 200, 90)

# ============================================================================
# 鼠标视角配置
# ============================================================================
## 鼠标水平移动转换为旋转弧度的灵敏度系数
MOUSE_SENSITIVITY = 0.0022
## 鼠标垂直移动转换为俯仰角的灵敏度系数
MOUSE_PITCH_SENSITIVITY = 0.0022
## 俯仰角上限（归一化值，相对半屏高度，1.0=半屏）
## 0.6≈±35°，0.85≈±75°（可看清天花板与地板）
PITCH_MAX = 0.85

# ============================================================================
# 疾跑配置
# ============================================================================
## 按住Shift时的移动速度倍率
SPRINT_MULTIPLIER = 1.8

# ============================================================================
# Win32虚拟键码
# ============================================================================
## 鼠标左键（用于mouse_controller检测点击切换视角）
VK_LBUTTON = 0x01

# ============================================================================
# 日志系统配置
# ============================================================================
## 日志配置文件路径
LOG_CONFIG_PATH = 'log_config.json'
## 默认全局日志级别
LOG_DEFAULT_LEVEL = 'WARNING'
## 默认日志文件路径
LOG_FILE_PATH = 'logs/game.log'
## 日志文件最大大小（字节，默认10MB）
LOG_MAX_BYTES = 10485760
## 日志文件备份数量
LOG_BACKUP_COUNT = 3
